export const GENRE_LIST: GenreDef[] = [GENRES.case, GENRES.breakdown, GENRES.invite, GENRES.response];

/** 組出送給 Maya 的完整提示詞（四層串接 + 輸出格式） */
export function buildGenrePrompt(brandKey: BrandKey, s: GenreSettings): string {
  const g = GENRES[s.genre];
  const lengthLine = s.length.trim() || `${g.lengthRange[0]}–${g.lengthRange[1]} 字（照文體建議）`;
  const variables = [
    "【本篇變數】",
    `主張（這篇要讓讀者接受的那一件事）：${s.claim.trim()}`,
    `${g.materialLabel}：${s.material.trim() || "（使用者未提供）"}`,
    s.metaphor.trim()
      ? `比喻：${s.metaphor.trim()}`
      : "比喻：使用者未指定。請自行提案一個，並在比喻出現的那一句後面加上【比喻待確認】讓使用者確認。",
    `長度：${lengthLine}`,
    s.cta.trim() ? `CTA：${s.cta.trim()}` : "CTA：使用者未指定，全文不放 CTA。",
  ].join("\n");

  return [
    SHARED_PREFIX,
    BRAND_TONES[brandKey],
    FUNNEL_RULES[s.funnel],
    g.skeleton,
    variables,
    `### 輸出 JSON 格式要求：
你必須且僅能輸出如下 JSON 代碼區塊（以 \`\`\`json 開始，以 \`\`\` 結束）：
{
  "social_copy": "完整文章，純文字，第一行是【標題】，禁止任何 Markdown 符號。缺素材的地方用【需補】標出並說明要補什麼。"
}`,
  ].join("\n\n");
}

export const GENRE_LIST: GenreDef[] = [GENRES.case, GENRES.breakdown, GENRES.invite, GENRES.fan, GENRES.response];

/** 組出送給 Maya 的完整提示詞（四層串接 + 輸出格式） */
export function buildGenrePrompt(brandKey: BrandKey, s: GenreSettings): string {
  const g = GENRES[s.genre];
  const lengthLine = s.length.trim() || `${g.lengthRange[0]} 到 ${g.lengthRange[1]} 字（照文體建議）`;
  const variables = [
    "【本篇變數】",
    `主張（這篇要讓讀者接受的那一件事）：${s.claim.trim()}`,
    `${g.materialLabel}：${s.material.trim() || "（使用者未提供）"}`,
    s.metaphor.trim()
      ? `比喻：${s.metaphor.trim()}`
      : "比喻：使用者未指定。請自行提案一個。文章裡不要加任何標記，改在 JSON 的 post_reminders 欄位寫一句「本篇的比喻是（寫出比喻），請發文前確認」。",
    `長度：${lengthLine}`,
    s.cta.trim() ? `CTA：${s.cta.trim()}` : "CTA：使用者未指定，全文不放 CTA。",
  ].join("\n");

  // 寵粉文的讀者是老客人，不套用給陌生人看的入口橋接規則，改用品牌領域寫法
  const entryBridge = s.genre === "fan" ? "" : buildEntryBridgePrompt(brandKey, s.funnel);
  const fanDomain = s.genre === "fan" ? BRAND_FAN_DOMAIN[brandKey] : "";

  return [
    SHARED_PREFIX,
    BRAND_TONES[brandKey],
    s.genre === "fan" ? FUNNEL_RULES.hot : FUNNEL_RULES[s.funnel],
    ...(entryBridge ? [entryBridge] : []),
    ...(fanDomain ? [fanDomain] : []),
    g.skeleton,
    variables,
    `### 輸出 JSON 格式要求：
你必須且僅能輸出如下 JSON 代碼區塊（以 \`\`\`json 開始，以 \`\`\` 結束）：
{
  "social_copy": "完整文章，純文字，第一行是【標題】，禁止任何 Markdown 符號。本文不可出現【需補】、待補或任何提醒字樣，缺素材的地方用泛稱情境帶過。",
  "post_reminders": ["發文前建議補上的真實素材，每項一句話，說明在第幾段補什麼。不需要補就給空陣列。這些提醒會顯示在文章外面，不會被發出去。"]
}`,
  ].join("\n\n");
}

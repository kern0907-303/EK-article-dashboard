// 引用規則：艾瑞克的寫作框架規定「引經據典只用自己的知識庫，先確認書與作者、讀過全文再引用，不憑記憶」。
// 2026-10-27 發現自動流水線完全沒有實作這條：15 篇已排程的 ABL 文章引了 15 本書，12 本不在知識庫裡。
// 這個檔只負責把規則寫成提示詞，純資料與純函式，不連資料庫、不呼叫網路，才能被測試直接載入。

/** 已查證的出處。null 代表這篇沒有拿到出處，就完全不准引用。 */
export interface VerifiedCitation { title: string; author: string }

/**
 * 引用規則指令。
 * 艾瑞克的規則是「引經據典只用自己的知識庫，讀過全文再引用，不憑記憶」。
 * 所以要嘛給它一本查證過的書與筆記內容，要嘛就完全禁止引用，沒有第三種。
 */
export function buildCitationDirective(citation: VerifiedCitation | null, noteContent: string): string {
  if (!citation) {
    return [
      "【引用規則】這一篇不可以引用任何書籍、作者、研究、調查或名人說法。",
      "不可以出現書名號《》。不可以寫「研究顯示」「專家指出」「科學家發現」這類沒有指名出處的說法。",
      "論點用場景、推理與你自己的觀察去支撐就好，不要借別人的權威。",
    ].join("\n");
  }
  return [
    "【引用規則】這一篇只能引用下面這一本書，不可以引用任何其他書籍、作者、研究或名人說法。",
    `可以引用的書：《${citation.title}》，作者${citation.author}`,
    "引用時要在句子裡寫明歸屬，格式是「《主書名》作者某某提出，（觀點）」，一句只歸屬一個觀點。",
    "故事與其他內容不可以寫成書裡的內容。書名只寫主書名，不要副標題。作者名與書名一律用中文。",
    "動詞用「提出」，不要用「核心概念是」這類評價說法。",
    `文末單獨一行：文中引用的觀點，出自${citation.author}所著《${citation.title}》。`,
    "如果這一篇用不到這本書，就完全不要引用，文末也不要寫出處。寧可不引用，也不可以引用別本。",
    "下面是這本書的筆記，只能依據它寫，不可以補上筆記裡沒有的說法：",
    String(noteContent || "").slice(0, 6000),
  ].join("\n");
}

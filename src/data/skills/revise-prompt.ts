// 修改模式的提示詞：自動流水線抓到品牌當主詞或引用不合格時，帶著問題句子要求模型修。
//
// 為什麼需要這個檔：原本的重寫是把「原始題目 + 四層風格指令 + 說話的人指令 + 引用指令
// （含最多數千字的書籍筆記）」整包再送一次，等於每次重寫都重新創作一篇。
// 一篇文章最多重寫三次，輸入量就是四倍。實際上要做的只是「改掉這幾句」，
// 所以改成只送上一版全文與問題清單，輸入量砍掉大半，也比較不會把寫好的部分改壞。
//
// 純資料與純函式，不連資料庫、不呼叫網路。

import type { VerifiedCitation } from "./citation-rules";

/**
 * @param draft 上一版全文
 * @param problems 必須修掉的問題，每則一句話
 * @param citation 這一篇查證過的出處；null 代表整篇不准引用
 */
export function buildRevisePrompt(draft: string, problems: string[], citation: VerifiedCitation | null, options?: { allowTitle?: boolean }): string {
  const allowTitle = options?.allowTitle === true;
  return [
    "【修改任務，不是重新創作】",
    "下面是上一版文章全文。請保留它的題目、結構、語氣、小標與大部分句子，只修掉被指出的問題，其他地方一個字都不要動。",
    allowTitle
      ? "不要重寫開場，不要調整段落順序，不要增減小標。標題被指出有問題，所以要重寫標題：場景必須是文章裡真的寫出來的畫面，一次讀完就要懂，最多兩個短句，不可以出現兩個否定詞，論點不變。"
      : "不要換題目，不要重寫開場，不要調整段落順序，不要增減小標。",
    "",
    "【上一版全文】",
    String(draft || ""),
    "",
    "【必須修掉的問題】",
    ...problems.map((item, index) => `${index + 1}. ${item}`),
    "",
    "【修改時要守住的規則】",
    "文章是艾瑞克這個人在說話，不是品牌在說話。品牌名稱後面不可以接任何動詞，只能當地點（例如我在平衡空間帶過一個案子）或服務名稱（例如平衡空間的生命數字）。品牌名稱全文最多出現一次，也不可以用「我們」替品牌發言。",
    citation
      ? `只能引用《${citation.title}》，作者${citation.author}。書名與作者只能用這個中文寫法，一個英文字母都不可以出現。用不到就完全不要引用。`
      : "不可以引用任何書籍、作者、研究或名人說法，不可以出現書名號。",
    "純文字，不要 Markdown 符號，不要破折號，不要加任何聲明或括號註記。",
    "",
    "輸出修改後的完整文章。",
  ].join("\n");
}

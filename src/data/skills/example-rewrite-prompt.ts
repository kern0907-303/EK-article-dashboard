// 換例子模式的提示詞。
//
// 為什麼需要這個檔：待處理中心原本只有兩種選擇，自己動手改字，或整篇重新生成。
// 整篇重新生成會換掉題目與論點，但艾瑞克要的是「題目方向不變，只有例子不妥、看不懂，把例子換掉」。
// 這個檔把那個要求寫成提示詞：鎖住標題、論點、結構與小標，只准動故事與舉例的段落。
//
// 純資料與純函式，不連資料庫、不呼叫網路。

/** 什麼叫做一個看得懂的例子。這是退稿最常見的原因，所以寫成明確標準而不是形容詞。 */
export const EXAMPLE_STANDARD = [
  "一個具體的人，在一個具體的場景，做一件具體的事。讀者要能在腦中看到畫面。",
  "三句話之內就要讓人知道發生了什麼事，不需要回頭重讀。",
  "用日常生活看得到的細節（時間、地點、動作、對話），不要用需要先解釋的比喻。",
  "不要用量子、能量場、頻率共振、磁場這類詞當比喻來解釋事情，那會讓例子更難懂。",
  "不要寫成「有些人會這樣」「很多人都」這種沒有主角的泛稱，要有一個人。",
  "人物可以是虛構的，可以有名字，這是刻意的設定。但不可以說成真實客戶或真實個案。",
  "不可以編造數字、成效、見證，例如三週改善八成、業績成長兩倍、客戶回報如何。",
].join("\n");

/**
 * 一個看得懂的標題要守住的條件。
 * 2026-10-29 實例：「簽下離婚協議那天，她把客廳十九年份的日曆一張張撕下來，沒有勇氣不是
 * 留下來的原因」。撕日曆的畫面文章裡沒有，「沒有勇氣不是原因」有兩個否定，三個短句用逗號
 * 黏在一起。三個問題都在這裡寫成明確條件。
 */
export const TITLE_STANDARD = [
  "標題寫的場景必須是文章裡真的寫出來的畫面。文章沒寫到的東西不可以出現在標題。",
  "一次讀完就要懂，不可以讓人回頭重讀。",
  "整個標題最多兩個短句，不要三句以上用逗號黏成一長串。",
  "不可以出現兩個否定詞，例如沒有什麼不是什麼的原因。要說就正面說。",
  "品牌名稱不要出現在標題裡，也不要當主詞。",
  "論點不變。換的是說法，不是換一個主題。",
].join("\n");

export interface ExampleRewriteInput {
  /** 上一版全文 */
  draft: string;
  /** 這一篇原本就引用的書名，null 代表原本沒引用、重寫後也不准引用 */
  keepCitationTitle: string | null;
  /** 艾瑞克自己寫的說明，例如哪一段看不懂。可留空 */
  note?: string;
  /** 上一輪重寫後仍然被抓到的問題，每則一句話 */
  problems?: string[];
  /** true 代表標題也要重寫。預設鎖住標題，只有他指定時才解鎖 */
  allowTitle?: boolean;
}

/**
 * 換例子的重寫指令。
 * 刻意不送原始題目與四層風格指令：那會變成重新創作，題目與論點就保不住。
 * 只送上一版全文加上「只能動哪裡」，模型照著改。
 */
export function buildExampleRewritePrompt(input: ExampleRewriteInput): string {
  const { draft, keepCitationTitle, note, problems, allowTitle } = input;
  const list = (problems || []).filter((item) => String(item || "").trim());
  return [
    "【換例子的修改任務，不是重新創作】",
    "下面是上一版文章全文。它的題目、論點與結論是對的，不要換。問題只在舉的例子不妥或讀者看不懂。",
    "",
    "【不可以動的部分】",
    ...(allowTitle ? [] : ["標題一個字都不要改。"]),
    "整篇的核心論點、立場與結論不要改，不要換成另一個主題。",
    "段落順序、小標數量與小標文字不要改。",
    "結尾的行動呼籲不要改。",
    "全文長度與上一版相近，不要變成另一種篇幅。",
    "",
    "【要換掉的部分】",
    allowTitle
      ? "標題，以及故事、情境與舉例的段落。換成同樣支撐原本論點、但讀者一看就懂的版本。"
      : "只換故事、情境與舉例的段落。換成同樣支撐原本論點、但讀者一看就懂的例子。",
    "",
    ...(allowTitle ? ["【標題要重寫，條件如下】", TITLE_STANDARD, ""] : []),
    "【什麼叫做一個看得懂的例子】",
    EXAMPLE_STANDARD,
    "",
    ...(note && note.trim() ? ["【艾瑞克指出的問題，優先處理】", note.trim(), ""] : []),
    ...(list.length ? ["【上一輪重寫後還是被抓到的問題，這次一定要修掉】", ...list.map((item, index) => `${index + 1}. ${item}`), ""] : []),
    "【還要守住的規則】",
    "文章是艾瑞克這個人在說話，不是品牌在說話。品牌名稱後面不可以接任何動詞，只能當地點（例如我在平衡空間帶過一個案子）或服務名稱（例如平衡空間的生命數字）。品牌名稱全文最多出現一次，也不可以用「我們」替品牌發言。",
    keepCitationTitle
      ? `原本引用的《${keepCitationTitle}》要保留原樣，書名與作者的寫法一個字都不要改。不可以換成別本書，不可以新增任何引用。`
      : "不可以引用任何書籍、作者、研究或名人說法，不可以出現書名號。上一版沒有引用，重寫後也不准有。",
    "純文字，不要 Markdown 符號（** 與 ##），不要破折號（——、—、─），不要加任何聲明或括號註記，例如「（故事情境為示意）」。",
    "",
    "【上一版全文】",
    String(draft || ""),
    "",
    "輸出換過例子之後的完整文章，不要加任何說明文字。",
  ].join("\n");
}
